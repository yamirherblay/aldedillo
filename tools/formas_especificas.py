# Atajos para escribir los modelos sin ruido.
def lin(*segs):
    return ["campos", [list(s) for s in segs]]


def cmp(etiqueta, nota=None, lineas=1):
    return ["campo", etiqueta, nota, lineas]


def tbl(cabeceras, anchos, filas=6, etiquetas=None, izquierda=(), alto=None,
        tam=None):
    b = ["tabla", cabeceras, filas, anchos]
    if etiquetas is not None or izquierda or alto or tam:
        b.append(etiquetas)
    if izquierda or alto or tam:
        b.append(list(izquierda))
    if alto or tam:
        b.append(alto)
    if tam:
        b.append(tam)
    return b


def tbl2(celdas, anchos, filas=6, izquierda=()):
    b = ["tabla_encabezado", [list(c) for c in celdas], filas, anchos]
    if izquierda:
        b.extend([1.0, 9, list(izquierda)])
    return b


def prr(texto):
    return ["parrafo", texto]


def subf(texto):
    return ["subtitulo_form", texto]


def firm(*bloques):
    return ["firmas", [list(b) for b in bloques]]


def nlin(n):
    return ["lineas", n]


def nueva():
    return ["pagina_nueva"]


def pc(texto):
    return ["parrafo_centrado", texto]


